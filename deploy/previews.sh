#!/bin/bash
# Runs a preview of every branch except main at https://<branch>.kikk.avecsans.studio, e.g.
# claude/fix-pins at claude-fix-pins.kikk.avecsans.studio. Called by deploy.sh after it
# fetched. A preview is rebuilt when its branch changes and removed with the branch.
#
# Containers run with compose.preview.yaml from main, never the branch's compose.yaml, so a
# branch can't change how it runs (a volume could mount the host). They get no .env: no
# Supabase (they serve the committed snapshot), no PostHog, and their own favorites.
set -euo pipefail

domain=kikk.avecsans.studio
max_previews=4
first_port=3100
previews=$HOME/previews
# Created by install.sh, owned by kikk. Caddy imports it.
caddy_file=/etc/caddy/sites/previews.kikk.avecsans.studio.caddy
repo=$(cd "$(dirname "$0")/.." && pwd)
compose_file=$repo/deploy/compose.preview.yaml

# Keep in sync with .github/workflows/preview-link.yml.
slugify() {
  tr '[:upper:]' '[:lower:]' <<<"$1" | sed -E 's/[^a-z0-9]+/-/g; s/^-+//' | cut -c1-60 |
    sed -E 's/-+$//'
}

compose() {
  local slug=$1
  shift
  PREVIEW_SOURCE=$previews/$slug PREVIEW_PORT=$(cat "$previews/$slug.port") \
    docker compose --project-name "kikk-preview-$slug" --file "$compose_file" "$@"
}

free_port() {
  local port
  for ((port = first_port; port < first_port + max_previews; port++)); do
    if ! cat "$previews"/*.port 2>/dev/null | grep -qx "$port"; then
      echo "$port"
      return
    fi
  done
  return 1
}

remove_stale() {
  local file slug
  for file in "$previews"/*.port; do
    [ -e "$file" ] || continue
    slug=$(basename "$file" .port)
    [ -n "${branches[$slug]-}" ] && continue

    echo "Removing the preview $slug"
    compose "$slug" down --volumes --rmi local || true
    git -C "$repo" worktree remove --force "$previews/$slug" 2>/dev/null || rm -rf "${previews:?}/$slug"
    rm -f "$previews/$slug.port" "$previews/$slug.sha"
  done
  git -C "$repo" worktree prune
}

update() {
  local slug branch sha port
  for slug in "${order[@]}"; do
    branch=${branches[$slug]}
    sha=$(git -C "$repo" rev-parse "origin/$branch")
    [ "$(cat "$previews/$slug.sha" 2>/dev/null)" = "$sha" ] && continue

    if [ ! -e "$previews/$slug.port" ]; then
      if ! port=$(free_port); then
        echo "No room for a preview of $branch, there are already $max_previews"
        continue
      fi
      echo "$port" >"$previews/$slug.port"
    fi

    echo "Previewing $branch at https://$slug.$domain: $(git -C "$repo" log --oneline -1 "$sha")"
    if [ -d "$previews/$slug" ]; then
      git -C "$previews/$slug" checkout --quiet --force --detach "$sha"
    else
      git -C "$repo" worktree add --quiet --detach "$previews/$slug" "$sha"
    fi
    # Remember it before building, so a broken build isn't retried every minute.
    echo "$sha" >"$previews/$slug.sha"
    compose "$slug" up --detach --build || echo "Building the preview of $branch failed"
  done
}

update_caddy() {
  local config file slug
  config="# Generated by deploy/previews.sh, edits are overwritten."$'\n'
  for file in "$previews"/*.port; do
    [ -e "$file" ] || continue
    slug=$(basename "$file" .port)
    config+="
$slug.$domain {
	encode zstd gzip
	header X-Robots-Tag \"noindex, nofollow\"
	reverse_proxy localhost:$(cat "$file")
}
"
  done

  printf '%s' "$config" | cmp -s - "$caddy_file" && return
  local previous
  previous=$(cat "$caddy_file")
  printf '%s' "$config" >"$caddy_file"
  # Through Caddy's admin API, no root needed. An invalid config would keep Caddy from
  # starting after a reboot, so put back the previous one if it's refused.
  if ! caddy reload --config /etc/caddy/Caddyfile; then
    echo "Caddy refused the preview config, restoring the previous one"
    printf '%s\n' "$previous" >"$caddy_file"
  fi
}

run() {
  # Previews start once install.sh has created the Caddy file.
  [ -w "$caddy_file" ] || exit 0
  mkdir -p "$previews"
  # Slug to branch, plus the slugs newest first, so new branches get free slots first.
  declare -gA branches=()
  order=()
  local branch slug
  while read -r branch; do
    case $branch in HEAD | main) continue ;; esac
    slug=$(slugify "$branch")
    # www.kikk.avecsans.studio already exists.
    case $slug in "" | www) continue ;; esac
    [ -n "${branches[$slug]-}" ] && continue
    branches[$slug]=$branch
    order+=("$slug")
  done < <(git -C "$repo" for-each-ref --sort=-committerdate \
    --format='%(refname:lstrip=3)' refs/remotes/origin)

  remove_stale
  update
  update_caddy
}

# Parse everything before running, deploy.sh may have just replaced this file.
run "$@"
exit
